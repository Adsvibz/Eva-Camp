const {_electron:electron}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path'),os=require('node:os')
const root=path.resolve(__dirname,'..'),data=fs.mkdtempSync(path.join(os.tmpdir(),'eva-update-ui-'))
let app
;(async()=>{
 app=await electron.launch({args:[path.join(root,'electron-update-test-bootstrap.cjs')],env:{...process.env,EVA_TEST_DATA_DIR:data},timeout:30000})
 const page=await app.firstWindow();page.setDefaultTimeout(30000)
 await page.locator('nav').getByRole('button',{name:'Preferences',exact:true}).click()
 const section=page.locator('.update-settings')
 await section.getByText('0.1.0',{exact:true}).waitFor()
 await section.getByRole('button',{name:'Check for updates',exact:true}).click()
 await section.getByRole('alert').filter({hasText:'Could not connect'}).waitFor()
 await app.evaluate(()=>{global.__updateOffline=false})
 await section.getByRole('button',{name:'Check for updates',exact:true}).click()
 await section.getByText('A new version is available.',{exact:true}).waitFor()
 await section.getByRole('button',{name:'Download update',exact:true}).click()
 await section.getByRole('button',{name:'Restart and install',exact:true}).waitFor()
 assert.equal((await page.evaluate(()=>window.eva.updateStatus())).phase,'ready')
 fs.mkdirSync(path.join(root,'test-results'),{recursive:true})
 await section.screenshot({path:path.join(root,'test-results/update-ready-en.png')})
 await page.locator('.preference-languages').getByRole('button',{name:'العربية',exact:true}).click()
 await section.getByRole('button',{name:'إعادة التشغيل والتثبيت',exact:true}).waitFor()
 await section.screenshot({path:path.join(root,'test-results/update-ready-ar.png')})
 // Confirm that cancellation leaves the app and the verified download available.
 await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:0,checkboxChecked:false})})
 assert.equal(await page.evaluate(()=>window.eva.installUpdate()),false)
 assert.equal((await page.evaluate(()=>window.eva.updateStatus())).phase,'ready')
 // The fixture intercepts only installer launch, after the real backup and DB close.
 await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:1,checkboxChecked:false})})
 const closed=app.waitForEvent('close',{timeout:30000})
 const install=page.evaluate(()=>window.eva.installUpdate()).catch(()=>{})
 await closed;await install;app=null
 const record=JSON.parse(fs.readFileSync(path.join(data,'update-install-record.json'),'utf8'))
 assert.equal(record.closedLive,true,'Database must be closed before installer launch')
 assert.equal(record.backups.length,1,'A pre-update backup must exist')
 assert.deepEqual(record.args.slice(0,3),['--updated','/S','--force-run'])
 assert.ok(record.args[3].startsWith('/D='))
 assert.equal(record.options.detached,true)
 console.log('PASS: in-app offline recovery, GitHub release detection, verified real installer download, English/Arabic update UI, install cancellation, pre-update backup, database closure before installer handoff.')
})().catch(error=>{console.error(error);process.exitCode=1}).finally(async()=>{if(app)await app.close().catch(()=>{});fs.rmSync(data,{recursive:true,force:true,maxRetries:3,retryDelay:200})})
