 const encoded=await app.evaluate(async({BrowserWindow},url)=>{
  const target=BrowserWindow.getAllWindows().find(w=>w.webContents.getURL()===url)
  if(!target)throw new Error('Missing print window')
  return (await target.webContents.printToPDF({pageSize:'A4',printBackground:true,preferCSSPageSize:true})).toString('base64')
 },url)
 const pdf=Buffer.from(encoded,'base64')
